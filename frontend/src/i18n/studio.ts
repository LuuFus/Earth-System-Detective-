function years(n: number): string {
  const d = n % 10;
  const dd = n % 100;
  if (d === 1 && dd !== 11) return 'рік';
  if (d >= 2 && d <= 4 && (dd < 12 || dd > 14)) return 'роки';
  return 'років';
}

